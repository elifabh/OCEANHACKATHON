#!/usr/bin/env python3
"""
make_dependencies.py - regenerate the package table inside DEPENDENCIES.md from
the environment that is actually installed.

WHY THIS SCRIPT EXISTS
The official rules require every third-party library to be listed with its
version number and licence. A hand-maintained list is wrong the moment anything
is upgraded, and nobody notices until a judge checks. Worse, a version number
typed from memory is a fabricated fact in a compliance document.

So the table is not written by hand. This script reads the installed
distributions, resolves the dependency tree from a declared root set so that
transitive libraries are included too, extracts each licence from package
metadata, and rewrites ONLY the marked region of DEPENDENCIES.md. Everything
outside the markers - data sources, attribution, the honest-limitations
section - is written by a human and is left untouched.

WHAT IT CANNOT DO
Package metadata is sometimes missing or vague about the licence. Anything this
script cannot determine is written as UNKNOWN and listed in a "must be checked
by hand" block. UNKNOWN entries must be resolved before anything is published.
The script never guesses a licence from the package name.

Usage:
    python src/make_dependencies.py --selftest
    python src/make_dependencies.py                 # rewrite DEPENDENCIES.md
    python src/make_dependencies.py --print         # stdout only, no write
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import date
from pathlib import Path

from importlib import metadata as md

DEPS_FILE = Path("DEPENDENCIES.md")
BEGIN = "<!-- BEGIN AUTOGENERATED: python packages -->"
END = "<!-- END AUTOGENERATED: python packages -->"

# The libraries this project imports directly. Transitive dependencies are
# discovered from these, so this list only needs the direct ones.
ROOTS = [
    "geopandas",
    "shapely",
    "pyproj",
    "rasterio",
    "numpy",
    "requests",
    "earthengine-api",
    "pandas",
    # Added 2026-08-28, national finish-out. Same class of gap as the
    # scikit-learn one below and found the same way - by walking every
    # import in src/ against this file rather than trusting the root set.
    #   pillow            src/ortho_check.py draws the footprint, crosshair
    #                     and scale bar on every orthophoto chip
    #   xarray            src/swell_direction.py reads the CMEMS NetCDF
    #   copernicusmarine  src/swell_direction.py --download,
    #                     src/site_wave_climate.py
    # xarray and copernicusmarine have been in use since 2026-08-10, when
    # they produced the LOCKED Sherkin swell axis behind 7.9 % / 15.2 %.
    # Eighteen days undeclared in a mandatory document.
    "pillow",
    "xarray",
    "copernicusmarine",
    # Added 2026-08-27. scikit-learn has been imported by the receptor screens
    # since 2026-08-11 (sklearn.cluster.DBSCAN clusters shore-proximate
    # buildings into settlements) but was never in this root set, so it was
    # absent from the generated table - a gap in a MANDATORY compliance
    # document, not a cosmetic one. Found while extending the screen
    # nationally.
    "scikit-learn",
]

# Distributions that ship with CPython or are packaging plumbing rather than a
# third-party library used by the project. Excluded to keep the table readable;
# named explicitly so the exclusion is auditable rather than silent.
SKIP = {"pip", "setuptools", "wheel", "pkg_resources", "distribute"}


def _normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _licence_of(dist: md.Distribution) -> str:
    """Best available licence string, or UNKNOWN. Never guessed."""
    meta = dist.metadata

    # PEP 639, the modern and unambiguous field.
    expr = meta.get("License-Expression")
    if expr and expr.strip():
        return expr.strip()

    # Trove classifiers are structured, so they beat the free-text field.
    classifiers = meta.get_all("Classifier") or []
    lic_classifiers = [c.split("::")[-1].strip() for c in classifiers
                       if c.startswith("License ::")]
    lic_classifiers = [c for c in lic_classifiers
                       if c.lower() not in ("osi approved",)]
    if lic_classifiers:
        return " / ".join(dict.fromkeys(lic_classifiers))

    # Free-text License field. Often the entire licence text, so only accept a
    # short value - a 20 kB blob in a table cell is not a licence name.
    lic = meta.get("License")
    if lic and lic.strip() and "\n" not in lic.strip() and len(lic.strip()) <= 60:
        return lic.strip()

    return "UNKNOWN"


def _requires(dist: md.Distribution) -> list[str]:
    """Direct runtime requirements, with extras and env markers dropped.

    A requirement carrying `extra == "..."` is optional and is not installed
    unless that extra was requested, so including it would list libraries the
    project does not actually use.
    """
    out = []
    for req in dist.requires or []:
        if "extra ==" in req:
            continue
        name = re.split(r"[\s\[<>=!;(~]", req.strip(), maxsplit=1)[0]
        if name:
            out.append(name)
    return out


def collect(roots: list[str]) -> tuple[list[dict], list[str]]:
    """Walk the dependency tree from the roots. Returns (rows, missing)."""
    installed = {}
    for dist in md.distributions():
        nm = dist.metadata.get("Name")
        if nm:
            installed[_normalise(nm)] = dist

    seen: set[str] = set()
    order: list[str] = []
    missing: list[str] = []
    queue = [_normalise(r) for r in roots]
    direct = set(queue)

    while queue:
        key = queue.pop(0)
        if key in seen:
            continue
        seen.add(key)
        dist = installed.get(key)
        if dist is None:
            missing.append(key)
            continue
        if key in SKIP:
            continue
        order.append(key)
        for dep in _requires(dist):
            dk = _normalise(dep)
            if dk not in seen and dk not in SKIP:
                queue.append(dk)

    rows = []
    for key in sorted(order):
        dist = installed[key]
        rows.append({
            "name": dist.metadata.get("Name") or key,
            "version": dist.version or "UNKNOWN",
            "licence": _licence_of(dist),
            "direct": key in direct,
        })
    return rows, missing


def render(rows: list[dict], missing: list[str]) -> str:
    """The markdown block that goes between the markers."""
    lines = [
        f"*Generated by `src/make_dependencies.py` on {date.today().isoformat()}"
        f" from Python {sys.version.split()[0]}. Do not edit by hand - rerun"
        " the script.*",
        "",
        "`direct` = imported by our own code. The rest are transitive"
        " dependencies pulled in by those, listed because the rules ask for"
        " every third-party library, not only the ones we import.",
        "",
        "| Package | Version | Licence | Direct |",
        "|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['name']} | {r['version']} | {r['licence']} | "
                     f"{'yes' if r['direct'] else '-'} |")

    unknown = [r for r in rows if r["licence"] == "UNKNOWN"]
    lines.append("")
    lines.append(f"**{len(rows)} packages, {len(unknown)} with an "
                 f"undetermined licence.**")
    if unknown:
        lines += [
            "",
            "> **MUST BE RESOLVED BEFORE PUBLICATION.** The metadata for these"
            " packages does not state a licence in a machine-readable field."
            " Read it off the project's repository or PyPI page and record it"
            " in the hand-written section below. This script does not guess.",
            "",
        ]
        for r in unknown:
            lines.append(f"> - {r['name']} {r['version']}")
    if missing:
        lines += [
            "",
            "> **NOT INSTALLED.** These are declared as roots in"
            " `src/make_dependencies.py` but are absent from this environment,"
            " so any code importing them will fail:",
            "",
        ]
        for m in missing:
            lines.append(f"> - `{m}`")
    lines.append("")
    return "\n".join(lines)


def rewrite(path: Path, block: str) -> str:
    """Replace only the marked region. Everything else is preserved verbatim."""
    text = path.read_text(encoding="utf-8")
    i, j = text.find(BEGIN), text.find(END)
    if i == -1 or j == -1:
        raise ValueError(
            f"markers not found in {path}. Expected these two lines:\n"
            f"  {BEGIN}\n  {END}")
    if j < i:
        raise ValueError("END marker appears before BEGIN marker")
    return text[:i + len(BEGIN)] + "\n\n" + block + "\n" + text[j:]


# ---------------------------------------------------------------------------
# Self-test
# ---------------------------------------------------------------------------

def selftest() -> int:
    import tempfile

    print("SELFTEST (no network)\n")

    assert _normalise("earthengine_api") == "earthengine-api"
    assert _normalise("Shapely") == "shapely"
    print("  name normalisation handles case, - and _  ok")

    rows, missing = collect(["numpy"])
    assert any(r["name"].lower() == "numpy" for r in rows), rows
    assert all(r["version"] != "UNKNOWN" for r in rows), rows
    print(f"  collect(['numpy']) -> {len(rows)} package(s), all versioned  ok")

    # A root that does not exist must be REPORTED, not silently dropped. This
    # is the failure that matters: a missing library that nobody notices.
    rows2, missing2 = collect(["numpy", "definitely-not-a-real-package-xyz"])
    assert "definitely-not-a-real-package-xyz" in missing2, missing2
    print("  a missing root is reported, not silently skipped  ok")

    # Transitive discovery must actually reach further than the roots.
    rows3, _ = collect(["geopandas"])
    names = {r["name"].lower() for r in rows3}
    assert len(rows3) > 1, rows3
    assert any(n in names for n in ("shapely", "pyproj", "pandas")), names
    direct = [r for r in rows3 if r["direct"]]
    assert len(direct) == 1 and direct[0]["name"].lower() == "geopandas"
    print(f"  transitive walk from geopandas -> {len(rows3)} packages, "
          f"1 marked direct  ok")

    # render() must surface UNKNOWN licences loudly rather than burying them.
    fake = [{"name": "aaa", "version": "1.0", "licence": "MIT", "direct": True},
            {"name": "bbb", "version": "2.0", "licence": "UNKNOWN",
             "direct": False}]
    out = render(fake, [])
    assert "MUST BE RESOLVED" in out and "bbb 2.0" in out, out
    clean = render([fake[0]], [])
    assert "MUST BE RESOLVED" not in clean, clean
    print("  render(): UNKNOWN licence raises a blocker, clean list does not"
          "  ok")

    # rewrite() must preserve text outside the markers, and refuse a file
    # without them rather than overwriting anything.
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "DEPENDENCIES.md"
        p.write_text(f"HEADER KEEP ME\n{BEGIN}\nold junk\n{END}\nFOOTER KEEP ME\n",
                     encoding="utf-8")
        new = rewrite(p, "NEW TABLE")
        assert "HEADER KEEP ME" in new and "FOOTER KEEP ME" in new, new
        assert "old junk" not in new, new
        assert "NEW TABLE" in new, new
        print("  rewrite(): outside-marker text preserved, inside replaced  ok")

        q = Path(d) / "no_markers.md"
        q.write_text("nothing here\n", encoding="utf-8")
        try:
            rewrite(q, "X")
            raise AssertionError("should have refused a file with no markers")
        except ValueError:
            pass
        print("  rewrite(): refuses a file without markers  ok")

    print("\nSELFTEST PASSED. Names normalise, missing roots are reported,")
    print("the transitive walk reaches past the roots, unknown licences are")
    print("escalated, and rewrite() cannot clobber hand-written prose.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Regenerate the package table in DEPENDENCIES.md.")
    ap.add_argument("--file", type=Path, default=DEPS_FILE)
    ap.add_argument("--print", dest="print_only", action="store_true",
                    help="print the block to stdout, write nothing")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    rows, missing = collect(ROOTS)
    block = render(rows, missing)

    if args.print_only:
        print(block)
        return 0

    if not args.file.exists():
        print(f"not found: {args.file}")
        print("Create it first (the hand-written sections are not generated),")
        print("including these two marker lines:")
        print(f"  {BEGIN}")
        print(f"  {END}")
        return 2
    try:
        new = rewrite(args.file, block)
    except ValueError as exc:
        print(f"cannot rewrite: {exc}")
        return 2
    args.file.write_text(new, encoding="utf-8")

    unknown = [r for r in rows if r["licence"] == "UNKNOWN"]
    print(f"  {args.file} updated: {len(rows)} packages")
    if unknown:
        print(f"  >>> {len(unknown)} packages have NO machine-readable licence")
        print("  >>> and are flagged in the file. Resolve them by hand before")
        print("  >>> publishing:")
        for r in unknown:
            print(f"        {r['name']} {r['version']}")
    if missing:
        print(f"  >>> {len(missing)} declared root(s) are NOT INSTALLED: "
              f"{missing}")
    return 0


if __name__ == "__main__":
    sys.exit(main())